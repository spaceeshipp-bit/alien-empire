#!/usr/bin/env python3
"""Generated battles, with expected results from the reference model (D-028),
plus two files built from config/balance: the stage specs the GDScript tests
compare sim/core/stage.gd against, and the config bundle the game ships with.

Writes sim/tests/generated/battles.json: battle specs drawn by tools/sim_cases.py
from a fixed seed, on the frozen golden config, each with the outcome, ticks,
checkpoints and final hash that tools/reference/sim_model.py gives. The golden
runner plays them through the GDScript loaders and the sim library on the
worker, the desktop and the phone, so the whole path from JSON to hash is
checked against an implementation written another way, on every platform.
tools/check_sim_native.py also plays them on the C++ core alone.

The first battle uses the largest seed a spec may have (2^53 - 1), which only
arrives exactly if the JSON reader is exact.

  python3 tools/gen_battles.py          # rewrite the file
  python3 tools/gen_battles.py --check  # exit 1 if it's out of date
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

import config_tool
import sim_cases
import stages
from reference import sim_model

REPO = Path(__file__).resolve().parent.parent
GOLDEN = REPO / "sim" / "tests" / "golden"
GENERATED = REPO / "sim" / "tests" / "generated" / "battles.json"
STAGE_SPECS = REPO / "sim" / "tests" / "generated" / "stage_specs.json"
CLIENT_BUNDLE = REPO / "client" / "data" / "config_bundle.json"
STAGE_SEED = 20261123
COUNT = 40
SEED = 20261111
MIN_ALIEN_TICKS = 2000  # alien moves across the battle
PROFILES = ("combat", "typical", "combat", "edges")


def expected(result: sim_model.Result) -> dict:
    """What a battle must end with, as sim/tests/golden/golden_runner.gd and
    tools/check_sim_native.py compare it."""
    return {
        "outcome": result.outcome,
        "ticks": result.ticks,
        "lives": result.lives,
        "credits_x100": result.credits_x100,
        "kills": result.kills,
        "leaked": result.leaked,
        "refused": result.refused,
        "spawned": result.spawned,
        "final_hash": result.final_hash,
        "checkpoints": result.checkpoints,
    }


def battles() -> dict:
    bundle = json.loads((GOLDEN / "config_bundle.json").read_text(encoding="utf-8"))
    out = []
    for i in range(COUNT):
        name = f"gen{i + 1:02d}"
        for attempt in range(1000):
            rnd = random.Random(f"aetd-generated-battles:{SEED}:{i}:{attempt}")
            spec = sim_cases.random_spec(rnd, bundle, PROFILES[i % len(PROFILES)], name)
            if i == 0:
                spec["seed"] = sim_cases.MAX_SEED
            result = sim_model.run(sim_cases.case_from_spec(bundle, spec, name))
            # Each battle the phone plays should have aliens on the move at several
            # checkpoints, and towers that kill some of them; the native fuzz already
            # covers empty and one-tick battles.
            fights = result.kills >= 1 or PROFILES[i % len(PROFILES)] == "edges"
            if result.entity_updates >= MIN_ALIEN_TICKS and len(result.checkpoints) >= 3 and fights:
                break
        else:
            raise SystemExit(f"error: no battle with enough movement for {name}")
        out.append({
            "name": name,
            "spec": spec,
            "expected": expected(result),
        })
    return {
        "about": "Generated by tools/gen_battles.py from the reference model. Do not edit by hand.",
        "sim_version": sim_model.MODEL_SIM_VERSION,
        "config_hash": bundle["config_hash"],
        "battles": out,
    }


def render(doc: dict) -> str:
    """One battle per line: compact, and a regenerated battle shows as one changed line."""
    head = {k: v for k, v in doc.items() if k != "battles"}
    lines = ["{"]
    lines += [f" {json.dumps(k)}: {json.dumps(v)}," for k, v in head.items()]
    lines.append(' "battles": [')
    lines.append(",\n".join("  " + json.dumps(b, separators=(",", ":")) for b in doc["battles"]))
    lines.append(" ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def stage_specs() -> str:
    """Each stage with the spec tools/stages.py builds for it, for the GDScript
    test that checks sim/core/stage.gd builds the same."""
    data = config_tool.load_balance()
    out = [{"stage": stage, "seed": STAGE_SEED, "spec": stages.build_spec(stage, STAGE_SEED)}
           for stage in data["stages"]["stages"]]
    return json.dumps({"about": "Generated by tools/gen_battles.py. Do not edit by hand.", "stages": out}, indent=1) + "\n"


def client_bundle() -> str:
    """The config the game ships with until the server serves it (M4)."""
    data = config_tool.load_balance()
    errors = config_tool.validate_balance(data)
    if errors:
        raise SystemExit("error: the balance config doesn't validate:\n" + "\n".join(errors))
    return json.dumps(config_tool.make_bundle(data), indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check the files are current")
    args = parser.parse_args(argv)
    outputs = {GENERATED: render(battles()), STAGE_SPECS: stage_specs(), CLIENT_BUNDLE: client_bundle()}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(REPO)} (run tools/gen_battles.py)", file=sys.stderr)
        return 1
    if args.check:
        print("generated battles, stage specs and the client's config bundle are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
