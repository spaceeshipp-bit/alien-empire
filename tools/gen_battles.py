#!/usr/bin/env python3
"""Generated battles, with expected results from the reference model (D-028).

Writes sim/tests/generated/battles.json: battle specs drawn by tools/sim_cases.py
from a fixed seed, on the frozen golden config, each with the outcome, ticks,
checkpoints and final hash that tools/reference/sim_model.py gives. The golden
runner plays them through the GDScript loaders and the sim library on the
worker, the desktop and the phone, so the whole path from JSON to hash is
checked against an implementation written another way, on every platform.
tools/check_sim_native.py also plays them on the C++ core alone.

The first battle uses the largest seed a spec may have (2^53 - 1), which only
arrives exactly if the JSON reader is exact.

  python3 tools/gen_battles.py          # rewrite the file
  python3 tools/gen_battles.py --check  # exit 1 if it's out of date
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

import sim_cases
from reference import sim_model

REPO = Path(__file__).resolve().parent.parent
GOLDEN = REPO / "sim" / "tests" / "golden"
GENERATED = REPO / "sim" / "tests" / "generated" / "battles.json"
COUNT = 40
SEED = 20261111
MIN_ALIEN_TICKS = 2000  # alien moves across the battle
PROFILES = ("typical", "edges")


def battles() -> dict:
    bundle = json.loads((GOLDEN / "config_bundle.json").read_text(encoding="utf-8"))
    out = []
    for i in range(COUNT):
        name = f"gen{i + 1:02d}"
        for attempt in range(1000):
            rnd = random.Random(f"aetd-generated-battles:{SEED}:{i}:{attempt}")
            spec = sim_cases.random_spec(rnd, bundle, PROFILES[i % len(PROFILES)], name)
            if i == 0:
                spec["seed"] = sim_cases.MAX_SEED
            result = sim_model.run(sim_cases.case_from_spec(bundle, spec, name))
            # Each battle the phone plays should have aliens on the move at several
            # checkpoints; the native fuzz already covers empty and one-tick battles.
            if result.entity_updates >= MIN_ALIEN_TICKS and len(result.checkpoints) >= 3:
                break
        else:
            raise SystemExit(f"error: no battle with enough movement for {name}")
        out.append({
            "name": name,
            "spec": spec,
            "expected": {
                "outcome": result.outcome,
                "ticks": result.ticks,
                "final_hash": result.final_hash,
                "checkpoints": result.checkpoints,
            },
        })
    return {
        "about": "Generated by tools/gen_battles.py from the reference model. Do not edit by hand.",
        "sim_version": sim_model.MODEL_SIM_VERSION,
        "config_hash": bundle["config_hash"],
        "battles": out,
    }


def render(doc: dict) -> str:
    """One battle per line: compact, and a regenerated battle shows as one changed line."""
    head = {k: v for k, v in doc.items() if k != "battles"}
    lines = ["{"]
    lines += [f" {json.dumps(k)}: {json.dumps(v)}," for k, v in head.items()]
    lines.append(' "battles": [')
    lines.append(",\n".join("  " + json.dumps(b, separators=(",", ":")) for b in doc["battles"]))
    lines.append(" ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check the file is current")
    args = parser.parse_args(argv)
    text = render(battles())
    current = GENERATED.read_text(encoding="utf-8") if GENERATED.exists() else None
    if args.check:
        if current != text:
            print(f"out of date: {GENERATED.relative_to(REPO)} (run tools/gen_battles.py)", file=sys.stderr)
            return 1
        print("generated battles up to date")
        return 0
    if current != text:
        GENERATED.parent.mkdir(parents=True, exist_ok=True)
        GENERATED.write_text(text, encoding="utf-8")
        print(f"wrote {GENERATED.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
