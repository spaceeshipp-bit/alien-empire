#!/usr/bin/env python3
"""Reference implementations of the sim's integer primitives, and the test
vectors the GDScript unit tests check on desktop, Android and headless.

  python3 tools/gen_vectors.py          # rewrite sim/tests/vectors/*.json
  python3 tools/gen_vectors.py --check  # exit 1 if the files are out of date

The RNG here must match sim/core/sim_rng.gd exactly (xoshiro128** seeded by
splitmix32). tools/reference/xoshiro128ss.c is a second, independent reference
in C that the pytest suite compares against this one.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VECTOR_DIR = REPO / "sim" / "tests" / "vectors"
MASK32 = 0xFFFFFFFF
MAX_SEED = 2**53 - 1


def mul32(a: int, b: int) -> int:
    return (a * b) & MASK32


def mul32_split(a: int, b: int) -> int:
    """The overflow-free form sim_rng.gd uses: no product exceeds 2^48."""
    low = (a * (b & 0xFFFF)) & MASK32
    high = ((a * (b >> 16)) & 0xFFFF) << 16
    return (low + high) & MASK32


def rotl(x: int, k: int) -> int:
    return ((x << k) | (x >> (32 - k))) & MASK32


class Rng:
    """Python twin of sim/core/sim_rng.gd."""

    def __init__(self, seed: int) -> None:
        if not 0 <= seed <= MAX_SEED:
            raise ValueError("seed out of range")
        lo = seed & MASK32
        hi = (seed >> 32) & MASK32
        self.sm = lo ^ mul32(hi, 0x85EBCA6B)
        self.s = [self._splitmix32() for _ in range(4)]
        if not any(self.s):
            self.s[0] = 1

    def _splitmix32(self) -> int:
        self.sm = (self.sm + 0x9E3779B9) & MASK32
        z = self.sm
        z = mul32(z ^ (z >> 16), 0x85EBCA6B)
        z = mul32(z ^ (z >> 13), 0xC2B2AE35)
        return z ^ (z >> 16)

    def next_u32(self) -> int:
        s0, s1, s2, s3 = self.s
        result = mul32(rotl(mul32(s1, 5), 7), 9)
        t = (s1 << 9) & MASK32
        s2 ^= s0
        s3 ^= s1
        s1 ^= s2
        s0 ^= s3
        s2 ^= t
        s3 = rotl(s3, 11)
        self.s = [s0, s1, s2, s3]
        return result

    def range_int(self, lo: int, hi: int) -> int:
        span = hi - lo + 1
        if span <= 1:
            return lo
        if span >= 2**32:
            return lo + self.next_u32()
        limit = 2**32 - (2**32 % span)
        r = self.next_u32()
        while r >= limit:
            r = self.next_u32()
        return lo + r % span

    def chance_bp(self, bp: int) -> bool:
        return self.range_int(0, 9999) < bp


RNG_SEEDS = [0, 1, 2, 42, 20261108, 2**32 - 1, 2**32, MAX_SEED]
# Each call: [op, args...]; the vector file adds the expected result.
RNG_SCRIPT = (
    [["u32"]] * 8
    + [["range", 0, 9]] * 8
    + [["range", -5, 5]] * 8
    + [["range", 0, 2**32 - 1]] * 3
    + [["range", 7, 7]] * 2
    + [["chance", 2500]] * 8
)


def rng_vectors() -> dict:
    cases = []
    for seed in RNG_SEEDS:
        rng = Rng(seed)
        calls = []
        for call in RNG_SCRIPT:
            if call[0] == "u32":
                calls.append(["u32", rng.next_u32()])
            elif call[0] == "range":
                calls.append(["range", call[1], call[2], rng.range_int(call[1], call[2])])
            else:
                calls.append(["chance", call[1], rng.chance_bp(call[1])])
        cases.append({"seed": seed, "calls": calls, "state_after": list(rng.s)})
    pick = random.Random(20261108)
    pairs = [(0, 0), (MASK32, MASK32), (MASK32, 1), (0x9E3779B9, 0x85EBCA6B), (0xC2B2AE35, 0xFFFF0000)]
    pairs += [(pick.getrandbits(32), pick.getrandbits(32)) for _ in range(16)]
    return {
        "about": "Generated by tools/gen_vectors.py. Do not edit by hand.",
        "rng": cases,
        "mul32": [[a, b, mul32(a, b)] for a, b in pairs],
    }


def isqrt_vectors() -> dict:
    values = set(range(0, 21))
    for root in (3, 99, 1000, 46340, 65535, 65536, 3037000, 94906265):
        values.update({root * root - 1, root * root, root * root + 1})
    values.update({2**31 - 1, 2**32, 10**12 + 7, 2**52, MAX_SEED})
    return {
        "about": "Generated by tools/gen_vectors.py. Do not edit by hand.",
        "isqrt": [[n, math.isqrt(n)] for n in sorted(values)],
    }


def hash_bytes(ops: list) -> bytes:
    """The byte stream sim/core/state_hasher.gd feeds to SHA-256."""
    out = bytearray()
    for op, value in ops:
        if op == "int":
            out += struct.pack("<q", value)
        else:
            utf8 = value.encode("utf-8")
            out += struct.pack("<q", len(utf8)) + utf8
    return bytes(out)


HASH_CASES = [
    ("empty", []),
    ("zero", [["int", 0]]),
    ("ints", [["int", 1], ["int", -1], ["int", 2**31], ["int", -(2**40)], ["int", MAX_SEED]]),
    ("strings", [["str", "swarmer"], ["str", ""], ["str", "héllo ✦"]]),
    ("mixed", [["int", 1], ["str", "38704caa"], ["int", 20], ["int", 0], ["str", "hive_carrier"]]),
]


def hash_vectors() -> dict:
    return {
        "about": "Generated by tools/gen_vectors.py. Do not edit by hand.",
        "cases": [
            {"name": name, "ops": ops, "sha256": hashlib.sha256(hash_bytes(ops)).hexdigest()}
            for name, ops in HASH_CASES
        ],
    }


def render(doc: dict) -> str:
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


FILES = {
    "rng_vectors.json": rng_vectors,
    "isqrt_vectors.json": isqrt_vectors,
    "hash_vectors.json": hash_vectors,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check the files are current")
    args = parser.parse_args(argv)
    stale = []
    for name, make in FILES.items():
        path = VECTOR_DIR / name
        text = render(make())
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        print("out of date: " + ", ".join(stale) + " (run tools/gen_vectors.py)", file=sys.stderr)
        return 1
    if args.check:
        print("vectors up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
