#!/usr/bin/env python3
"""Writes the placeholder sprites and palette the game loads (D-031).

    python3 tools/art/build_art.py            # write client/art/
    python3 tools/art/build_art.py --check    # fail if client/art/ is out of date
    python3 tools/art/build_art.py --preview  # also render docs/art/cast_sheet.png

The preview needs Node and Playwright with Chromium; the sprites need neither.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sheets  # noqa: E402
import sprites  # noqa: E402

ROOT = HERE.parent.parent
ART = ROOT / "client" / "art"
PREVIEW = ROOT / "docs" / "art" / "cast_sheet.png"


def _godot_color(hex_color: str) -> str:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return f"Color({r:.4f}, {g:.4f}, {b:.4f})  # {hex_color}"


def palette_gd() -> str:
    """The colors as GDScript constants, so the game and the sprites share one source."""
    lines = [
        "extends RefCounted",
        "## Generated by tools/art/build_art.py from tools/art/sprites.py. Don't edit:",
        "## change the palette there and run the tool. What each color means is in docs/ART.md.",
        "",
    ]
    named = [
        ("GROUND", sprites.GROUND), ("GROUND_2", sprites.GROUND_2), ("PANEL", sprites.PANEL), ("PANEL_2", sprites.PANEL_2),
        ("TEXT", sprites.TEXT), ("MUTED", sprites.MUTED), ("YOU", sprites.YOU), ("YOU_DEEP", sprites.YOU_DEEP),
        ("CLAN", sprites.CLAN), ("RIVAL", sprites.RIVAL), ("HIVE", sprites.HIVE), ("DANGER", sprites.DANGER),
        ("SHELL", sprites.SHELL), ("EYE", sprites.EYE), ("METAL", sprites.METAL), ("HEAT", sprites.HEAT), ("ION", sprites.ION),
    ]
    lines += [f"const {name} := {_godot_color(value)}" for name, value in named]
    lines += ["", "## Class colors (D-032), keyed by the class names in config/balance/.", "const CLASS_COLORS := {"]
    lines += [f'\t"{kind}": {_godot_color(v["color"])}' .replace("  #", ",  #") for kind, v in sprites.CLASSES.items()]
    lines += ["}", ""]
    return "\n".join(lines)


def expected_files() -> dict[str, str]:
    files = dict(sprites.sprite_files())
    files["palette.gd"] = palette_gd()
    return files


def problems() -> list[str]:
    """What's missing, stale or unexpected in client/art/ (import files aside)."""
    expected = expected_files()
    found = {p.relative_to(ART).as_posix() for p in ART.rglob("*") if p.is_file() and p.suffix in (".svg", ".gd")} if ART.exists() else set()
    out = []
    for rel, text in sorted(expected.items()):
        path = ART / rel
        if not path.exists():
            out.append(f"missing: client/art/{rel}")
        elif path.read_text(encoding="utf-8") != text:
            out.append(f"out of date: client/art/{rel}")
    out += [f"not made by the tool: client/art/{rel}" for rel in sorted(found - set(expected))]
    return out


def write() -> None:
    for rel, text in expected_files().items():
        path = ART / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote client/art/{rel}")


def preview() -> None:
    PREVIEW.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        svg = Path(tmp) / "cast_sheet.svg"
        svg.write_text(sheets.cast_sheet(), encoding="utf-8")
        w, h = sheets.SIZE
        subprocess.run(["node", str(HERE / "render.cjs"), str(svg), str(PREVIEW), str(w), str(h)], check=True)
    print(f"rendered {PREVIEW.relative_to(ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if client/art/ is out of date")
    parser.add_argument("--preview", action="store_true", help="also render the cast sheet PNG")
    args = parser.parse_args()
    if args.check:
        found = problems()
        for line in found:
            print(line)
        if found:
            print("Run: python3 tools/art/build_art.py")
            return 1
        print(f"client/art/ is current ({len(expected_files())} files)")
        return 0
    write()
    if args.preview:
        preview()
    return 0


if __name__ == "__main__":
    sys.exit(main())
